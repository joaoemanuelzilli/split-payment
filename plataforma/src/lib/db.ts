// Banco Postgres. Em produção, DATABASE_URL aponta para o Supabase (pooler de transação, porta 6543).
// Sem DATABASE_URL, roda um Postgres embutido (PGlite) em data/pg, para desenvolvimento e testes.

/** Agora em UTC no formato que a aplicação guarda (texto 'AAAA-MM-DD HH:MM:SS'). */
export const AGORA = "to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')";
export const HA_30_DIAS = "to_char(timezone('utc', now() - interval '30 days'), 'YYYY-MM-DD HH24:MI:SS')";

const ID = 'integer generated by default as identity primary key';
const TABELAS = ['settings', 'parceiros', 'usuarios', 'sessoes', 'empresas', 'simulacoes', 'checklist', 'notas', 'parametros_historico'];

// O bloqueio faz duas instâncias que sobem juntas criarem as tabelas uma de cada vez.
const ESQUEMA = `
SELECT pg_advisory_xact_lock(732001);
CREATE TABLE IF NOT EXISTS settings (
  chave text PRIMARY KEY, valor text NOT NULL, atualizado_em text NOT NULL DEFAULT ${AGORA});
CREATE TABLE IF NOT EXISTS parceiros (
  id ${ID}, slug text UNIQUE NOT NULL, nome text NOT NULL, cor text, logo_url text,
  contato_nome text, email text, telefone text, cidade text, repasse_pct double precision NOT NULL DEFAULT 20,
  ativo integer NOT NULL DEFAULT 1, criado_em text NOT NULL DEFAULT ${AGORA});
CREATE TABLE IF NOT EXISTS usuarios (
  id ${ID}, email text UNIQUE NOT NULL, nome text NOT NULL, senha_hash text NOT NULL,
  papel text NOT NULL CHECK (papel IN ('admin','consultor','parceiro')), parceiro_id integer REFERENCES parceiros(id),
  ativo integer NOT NULL DEFAULT 1, criado_em text NOT NULL DEFAULT ${AGORA});
CREATE TABLE IF NOT EXISTS sessoes (
  token text PRIMARY KEY, usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE, expira_em text NOT NULL);
CREATE TABLE IF NOT EXISTS empresas (
  id ${ID}, nome text NOT NULL, cnpj text, nicho_id text, cidade text, uf text,
  contato_nome text, cargo text, email text, telefone text, faturamento_mensal double precision,
  etapa text NOT NULL DEFAULT 'lead', origem text NOT NULL DEFAULT 'manual',
  responsavel_id integer REFERENCES usuarios(id), parceiro_id integer REFERENCES parceiros(id),
  observacoes text, consentimento integer NOT NULL DEFAULT 0,
  criado_em text NOT NULL DEFAULT ${AGORA}, atualizado_em text NOT NULL DEFAULT ${AGORA});
CREATE INDEX IF NOT EXISTS empresas_etapa ON empresas(etapa);
CREATE INDEX IF NOT EXISTS empresas_parceiro ON empresas(parceiro_id);
CREATE TABLE IF NOT EXISTS simulacoes (
  id ${ID}, empresa_id integer REFERENCES empresas(id) ON DELETE CASCADE, nicho_id text NOT NULL,
  nome text NOT NULL, valores text NOT NULL, parametros text NOT NULL, caixa text NOT NULL, resumo text NOT NULL,
  versao_base text NOT NULL, token text UNIQUE NOT NULL, criado_por integer REFERENCES usuarios(id),
  criado_em text NOT NULL DEFAULT ${AGORA}, atualizado_em text NOT NULL DEFAULT ${AGORA});
CREATE INDEX IF NOT EXISTS simulacoes_empresa ON simulacoes(empresa_id);
CREATE TABLE IF NOT EXISTS checklist (
  id ${ID}, empresa_id integer NOT NULL REFERENCES empresas(id) ON DELETE CASCADE,
  tipo text NOT NULL CHECK (tipo IN ('pergunta','documento','tarefa')), texto text NOT NULL,
  feito integer NOT NULL DEFAULT 0, resposta text, ordem integer NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS checklist_empresa ON checklist(empresa_id);
CREATE TABLE IF NOT EXISTS notas (
  id ${ID}, empresa_id integer NOT NULL REFERENCES empresas(id) ON DELETE CASCADE,
  usuario_id integer REFERENCES usuarios(id), texto text NOT NULL, criado_em text NOT NULL DEFAULT ${AGORA});
CREATE INDEX IF NOT EXISTS notas_empresa ON notas(empresa_id);
CREATE TABLE IF NOT EXISTS parametros_historico (
  id ${ID}, valores text NOT NULL, motivo text, usuario_id integer REFERENCES usuarios(id),
  criado_em text NOT NULL DEFAULT ${AGORA});
${TABELAS.map(t => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
DO $$ BEGIN
  -- No Supabase, nada destas tabelas fica acessível pela API pública: só o servidor da plataforma lê e grava.
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ${TABELAS.join(', ')} FROM anon, authenticated;
  END IF;
END $$;
`;

interface Conexao { query(texto: string, params: unknown[]): Promise<Record<string, unknown>[]> }
type G = typeof globalThis & { __conexao?: Promise<Conexao> };
const g = globalThis as G;

async function abrir(): Promise<Conexao> {
  const url = process.env.DATABASE_URL;
  if (url) {
    const postgres = (await import('postgres')).default;
    const local = /@(localhost|127\.0\.0\.1|db)(:|\/)/.test(url);
    const sql = postgres(url, {
      prepare: false, // exigido pelo pooler de transação do Supabase
      max: Number(process.env.PG_MAX_CONEXOES) || (process.env.VERCEL ? 1 : 5),
      idle_timeout: 20,
      ssl: local ? false : 'require',
      onnotice: () => {},
    });
    await sql.unsafe(ESQUEMA);
    return { query: (t, p) => sql.unsafe(t, p as never[]) as unknown as Promise<Record<string, unknown>[]> };
  }
  const { PGlite } = await import('@electric-sql/pglite');
  const pg = new PGlite(process.env.PGLITE_DIR || path.join(process.cwd(), 'data', 'pg'));
  await pg.exec(ESQUEMA);
  return { query: async (t, p) => (await pg.query<Record<string, unknown>>(t, p)).rows };
}

function conexao() {
  if (!g.__conexao) g.__conexao = abrir().catch(e => { g.__conexao = undefined; throw e; });
  return g.__conexao;
}

/** Troca os `?` da consulta por $1, $2... (as consultas da aplicação não usam `?` dentro de textos). */
const numerar = (texto: string) => { let i = 0; return texto.replace(/\?/g, () => `$${++i}`); };

export async function todos<T>(texto: string, params: unknown[] = []): Promise<T[]> {
  return (await (await conexao()).query(numerar(texto), params)) as T[];
}
export async function um<T>(texto: string, params: unknown[] = []): Promise<T | undefined> {
  return (await todos<T>(texto, params))[0];
}
export async function executar(texto: string, params: unknown[] = []): Promise<void> {
  await todos(texto, params);
}

const lerSetting = cache(async (chave: string) => (await um<{ valor: string }>('SELECT valor FROM settings WHERE chave = ?', [chave]))?.valor);

export async function getSetting<T extends object>(chave: string, padrao: T): Promise<T> {
  const valor = await lerSetting(chave);
  if (valor == null) return padrao;
  try {
    const v = JSON.parse(valor);
    return Array.isArray(padrao) ? (v as T) : ({ ...padrao, ...v } as T);
  } catch {
    return padrao;
  }
}

export async function setSetting(chave: string, valor: unknown) {
  await executar(
    `INSERT INTO settings (chave, valor, atualizado_em) VALUES (?, ?, ${AGORA})
     ON CONFLICT (chave) DO UPDATE SET valor = excluded.valor, atualizado_em = excluded.atualizado_em`,
    [chave, JSON.stringify(valor)],
  );
}
